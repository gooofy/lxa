#define DIR "T:lxaprobe_libdir"
#define FILE DIR "/p237probe.library"

int main(void)
{
    struct Library *lib;
    BPTR dir, old, fh;

    dir = CreateDir(DIR);
    if (dir)
        UnLock(dir);
    fh = Open(FILE, MODE_NEWFILE);
    if (!fh) {
        probe_s("cannot write " FILE "\n");
        return 0;
    }
    Write(fh, (APTR)plib, sizeof(plib));
    Close(fh);

    P_SECTION("OpenLibrary of a library outside LIBS:");
    lib = OpenLibrary("p237probe.library", 0);
    P_NULL("from another directory", lib);
    if (lib)
        CloseLibrary(lib);

    dir = Lock(DIR, SHARED_LOCK);
    old = CurrentDir(dir);
    lib = OpenLibrary("p237probe.library", 0);
    P_NULL("from its directory", lib);
    if (lib) {
        P_LONG("lib_Version", lib->lib_Version);
        P_STR("ln_Name", lib->lib_Node.ln_Name);
        CloseLibrary(lib);
    }
    CurrentDir(old);
    UnLock(dir);

    /* resident now: found from anywhere */
    lib = OpenLibrary("p237probe.library", 0);
    P_NULL("again from another directory", lib);
    if (lib) {
        CloseLibrary(lib);
        Forbid();
        RemLibrary(lib);
        Permit();
    }
    DeleteFile(FILE);
    DeleteFile(DIR);
    return 0;
}
