int main(void)
{
    BPTR fh, dir, old;
    struct Library *lib;

    fh = Open((STRPTR)"T:probeinit.library", MODE_NEWFILE);
    if (!fh)
        return 20;
    Write(fh, (APTR)libfile, sizeof(libfile));
    Close(fh);
    dir = Lock((STRPTR)"T:", SHARED_LOCK);
    old = CurrentDir(dir);
    lib = OpenLibrary((STRPTR)"probeinit.library", 0);
    P_BOOL("opened", lib != NULL);
    if (lib) {
        P_LONG("version", lib->lib_Version);
        P_LONG("open count", lib->lib_OpenCnt);
        probe_s("name = ");
        probe_s(lib->lib_Node.ln_Name);
        probe_ch('\n');
        CloseLibrary(lib);
    }
    CurrentDir(old);
    UnLock(dir);
    DeleteFile((STRPTR)"T:probeinit.library");
    return 0;
}
